// Sync the bot's data from the web app's data.js — run after the
// web app data changes (new weapons, tier moves, new patches).
//   node tools/sync_data.js
// Reads ../mw4-tracker-webapp/data.js (window.MW4_DATA) and writes
// src/data.js as a Node module. Nothing is retyped or invented.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'mw4-tracker-webapp', 'data.js');
const DEST = path.join(__dirname, '..', 'src', 'data.js');

const src = fs.readFileSync(SRC, 'utf8');
const window = {};
eval(src); // data.js only assigns window.MW4_DATA; no side effects.
const data = window.MW4_DATA;

const weapons = data.weapons.length;
const camos = data.weapons.reduce((n, w) => n + w.camos.length, 0);
if (weapons !== 37 || camos !== 222) {
  console.error(`Unexpected counts: ${weapons} weapons, ${camos} camos (expected 37 / 222). Aborting.`);
  process.exit(1);
}

const out =
  '// Generated by tools/sync_data.js from the MW4 Tracker web app\n' +
  '// (../mw4-tracker-webapp/data.js). Do not edit by hand — re-run\n' +
  '// `node tools/sync_data.js` after the web app data changes.\n' +
  'module.exports = ' + JSON.stringify(data, null, 1) + ';\n';

fs.mkdirSync(path.dirname(DEST), { recursive: true });
fs.writeFileSync(DEST, out);
console.log(`Wrote ${DEST} (${weapons} weapons, ${camos} camos).`);
